def emit_strategy(thesis: str, rules_path_or_json: str, framework: str, out_path: str):
    print(f"[StrategyEmitter] Emitting {framework} strategy code for thesis: '{thesis}'...")
    
    # Class name formatting
    clean_thesis = "".join([c for c in thesis.title() if c.isalnum()])
    class_name = f"{clean_thesis}Strategy" if clean_thesis else "NujinSkillStrategy"
    
    if framework.lower() == "jesse":
        code = JESSE_TEMPLATE.format(thesis=thesis, class_name=class_name)
    else:
        code = FREQTRADE_TEMPLATE.format(thesis=thesis, class_name=class_name)
        
    os.makedirs(os.path.dirname(os.path.abspath(out_path)), exist_ok=True)
    with open(out_path, "w") as f:
        f.write(code.strip() + "\n")
        
    print(f"[StrategyEmitter] Strategy script successfully generated: {out_path}")

if __name__ == "__main__":
    parser = argparse.ArgumentParser(description="Strategy Code Emitter CLI")
    parser.add_argument("--thesis", required=True, help="Economic thesis description")
    parser.add_argument("--rules", default="{}", help="Rules JSON string or path")
    parser.add_argument("--framework", choices=["freqtrade", "jesse"], default="freqtrade", help="Target strategy framework")
    parser.add_argument("--out", required=True, help="Output python strategy file path")
    args = parser.parse_args()
    
    emit_strategy(args.thesis, args.rules, args.framework, args.out)
